import type { ComponentProps } from 'react'
import manifest from '@/features/landing/media-manifest.json'
import variantManifest from '@/features/landing/media-variants.json'

const assets: Readonly<Record<string, string>> = manifest
type Variants = { width: number; height: number; widths: number[] }
const variants: Readonly<Record<string, Variants>> = variantManifest

/** Masters up to this width are also offered in srcSet; larger ones are capped. */
const MAX_MASTER_WIDTH = 1920

export function mediaUrl(src: string) {
  return assets[src] ?? src
}

const variantUrl = (local: string, width: number) =>
  local.replace(/\.[^.]+$/, `-${width}w.webp`)

/** Responsive sources generated by scripts/optimize-media.mjs, or null for other images. */
export function responsiveSources(src: string) {
  const local = mediaUrl(src)
  const entry = variants[local]
  if (!entry) return null
  const candidates = entry.widths.map((w) => `${variantUrl(local, w)} ${w}w`)
  if (entry.width <= MAX_MASTER_WIDTH)
    candidates.push(`${local} ${entry.width}w`)
  const largest = entry.widths.at(-1)
  return {
    src:
      entry.width <= MAX_MASTER_WIDTH || largest === undefined
        ? local
        : variantUrl(local, largest),
    srcSet: candidates.join(', '),
    width: entry.width,
    height: entry.height,
  }
}

type ImageProps = Omit<ComponentProps<'img'>, 'src' | 'alt'> & {
  src: string
  alt: string
  fill?: boolean
  priority?: boolean
}

/** Native local images; fill containers retain the source layout and aspect ratio. */
export function Image({
  src,
  alt,
  fill,
  priority,
  style,
  loading,
  srcSet,
  sizes,
  width,
  ...props
}: ImageProps) {
  const responsive = srcSet ? null : responsiveSources(src)
  return (
    <img
      {...props}
      src={responsive?.src ?? mediaUrl(src)}
      srcSet={srcSet ?? responsive?.srcSet}
      sizes={
        sizes ??
        (srcSet || responsive ? (width ? `${width}px` : '100vw') : undefined)
      }
      width={width}
      alt={alt}
      loading={priority ? 'eager' : (loading ?? 'lazy')}
      fetchPriority={priority ? 'high' : props.fetchPriority}
      decoding={priority ? 'sync' : 'async'}
      style={
        fill
          ? {
              position: 'absolute',
              inset: 0,
              width: '100%',
              height: '100%',
              ...style,
            }
          : style
      }
    />
  )
}
